"""Rebuild the site's font subset: pip install fonttools brotli; python scripts/subset-font.py."""
from pathlib import Path
import subprocess
import hashlib
import re
from html import unescape
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / 'assets/fonts'
source = FONT_DIR / 'PretendardVariable.woff2'
chars = set(range(32, 127)) | set(range(0x2000, 0x2070)) | {0xA0, 0x25E6, 0x25AA}
for name in subprocess.check_output(['git', 'ls-files'], cwd=ROOT, text=True).splitlines():
    if name.endswith(('.html', '.js', '.json')):
        chars.update(map(ord, unescape((ROOT / name).read_text(encoding='utf-8'))))
font = TTFont(source, recalcTimestamp=False)
supported = set(font.getBestCmap())
used = chars & supported

def unicode_ranges(points):
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in runs)

options = subset.Options()
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=used)
subsetter.subset(font)
font.save(FONT_DIR / 'PretendardSite.woff2')
digest = hashlib.sha256((FONT_DIR / 'PretendardSite.woff2').read_bytes()).hexdigest()[:10]
faces = []
for filename, points in [('PretendardSite.woff2', used), ('PretendardVariable.woff2', supported - used)]:
    faces.append(f'''@font-face {{
  font-family: "Pretendard";
  src: url("{filename}{"?v=" + digest if filename == "PretendardSite.woff2" else ""}") format("woff2");
  font-style: normal;
  font-weight: 100 900;
  font-display: block;
  unicode-range: {unicode_ranges(points)};
}}
''')
(FONT_DIR / 'fonts.css').write_text('/* Generated by scripts/subset-font.py. */\n' + '\n'.join(faces), encoding='utf-8')
print(f'{len(used)} codepoints: {source.stat().st_size:,} -> {(FONT_DIR / "PretendardSite.woff2").stat().st_size:,} bytes')

for name in ['index.html', 'post.html']:
    path = ROOT / name
    markup = path.read_text(encoding='utf-8')
    markup = re.sub(r'PretendardSite\.woff2(?:\?v=[a-zA-Z0-9-]+)?', 'PretendardSite.woff2?v=' + digest, markup)
    path.write_text(markup, encoding='utf-8')
